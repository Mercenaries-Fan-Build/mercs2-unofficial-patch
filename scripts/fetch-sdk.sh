#!/usr/bin/env bash
# Fetch the pinned mercs2-sdk release from GitHub and populate .sdk/<version>/ with the files
# a mod needs to build against the shared layer.
#
# The release ships three independent assets:
#   - m2-sdk-<ver>-headers.zip  → unpacked under .sdk/<ver>/include/m2/
#   - libm2-sdk.dll.a           → placed at .sdk/<ver>/lib/libm2-sdk.dll.a
#   - m2-sdk.dll                → placed at .sdk/<ver>/runtime/m2-sdk.dll
#
# A `sdk.mk` adapter is generated at .sdk/<ver>/sdk.mk so a mod Makefile can just
# `include ../.sdk/<ver>/sdk.mk` and link via $(M2_CFLAGS) / $(M2_LDFLAGS) / $(M2_IMPLIB).
#
# Pin values. Bump these when upgrading. The sha256 of each asset is pinned so a mutated
# release cannot slip in silently; the script hard-fails on mismatch.
SDK_VERSION="v0.6.0"
SDK_HEADERS_SHA256="01513ec28164ae5ac91b23b08e6d8fcebf2aff05c64cff8523481163df8130cc"
SDK_IMPLIB_SHA256="fc079b5d04b79030414be803f91775860f2acbb42b895f427bedffb85bcae563"
SDK_RUNTIME_SHA256="0fbabf91a988de0553144fd36d9df111994ea2208fd45113d7e8019190231ec7"

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

TARGET=".sdk/$SDK_VERSION"
if [ -f "$TARGET/sdk.mk" ] && [ -f "$TARGET/lib/libm2-sdk.dll.a" ] && [ -f "$TARGET/runtime/m2-sdk.dll" ]; then
    echo "mercs2-sdk $SDK_VERSION already fetched at $TARGET"
    exit 0
fi

mkdir -p "$TARGET/include/m2" "$TARGET/lib" "$TARGET/runtime"

BASE_URL="https://github.com/Mercenaries-Fan-Build/mercs2-sdk/releases/download/$SDK_VERSION"

download_and_verify() {
    local url="$1" out="$2" expected_sha="$3"
    local label
    label="$(basename "$out")"
    echo "fetching $label..."
    curl -fsSL -o "$out" "$url"
    local actual_sha
    actual_sha="$(shasum -a 256 "$out" | awk '{print $1}')"
    if [ "$actual_sha" != "$expected_sha" ]; then
        echo "sha256 mismatch for $label" >&2
        echo "  expected: $expected_sha" >&2
        echo "  actual:   $actual_sha" >&2
        rm -f "$out"
        exit 1
    fi
}

HEADERS_ZIP="$TARGET/headers.zip"
download_and_verify "$BASE_URL/m2-sdk-$SDK_VERSION-headers.zip" "$HEADERS_ZIP" "$SDK_HEADERS_SHA256"
unzip -q -o -d "$TARGET/include/m2" "$HEADERS_ZIP"
rm -f "$HEADERS_ZIP"

download_and_verify "$BASE_URL/libm2-sdk.dll.a" "$TARGET/lib/libm2-sdk.dll.a" "$SDK_IMPLIB_SHA256"
download_and_verify "$BASE_URL/m2-sdk.dll" "$TARGET/runtime/m2-sdk.dll" "$SDK_RUNTIME_SHA256"

# Generate the sdk.mk adapter. Mirrors the variable names the submodule-era sdk.mk exported, so
# consumers only have to swap the `include` path. MinHook headers are intentionally not advertised:
# the released SDK's public headers reference MinHook only in comments, not in the API.
cat > "$TARGET/sdk.mk" <<'ADAPTER'
# Auto-generated by scripts/fetch-sdk.sh — do not edit by hand.
# Pinned mercs2-sdk release (see SDK_VERSION in the fetch script).
#
# Include this from a mod Makefile and link via $(M2_CFLAGS), $(M2_LDFLAGS), $(M2_IMPLIB):
#   include ../.sdk/<version>/sdk.mk
#   $(CC) $(CFLAGS) $(M2_CFLAGS) -o mod.asi mod.c $(M2_LDFLAGS)
#
# Paths resolve relative to the including Makefile's directory via MAKEFILE_LIST.
M2_SDK_DIR := $(patsubst %/,%,$(dir $(lastword $(MAKEFILE_LIST))))

M2_CFLAGS  := -I$(M2_SDK_DIR)/include/m2
M2_DLL     := $(M2_SDK_DIR)/runtime/m2-sdk.dll
M2_IMPLIB  := $(M2_SDK_DIR)/lib/libm2-sdk.dll.a
M2_LDFLAGS := -L$(M2_SDK_DIR)/lib -lm2-sdk
ADAPTER

echo "mercs2-sdk $SDK_VERSION ready at $TARGET"
